export default function Guide() {
  const [active, setActive] = useState(CHAPTERS[0].id)

  useEffect(() => {
    const fn = () => {
      let cur = CHAPTERS[0].id
      for (const c of CHAPTERS) {
        const el = document.getElementById(c.id)
        if (el && el.getBoundingClientRect().top <= 120) cur = c.id
      }
      setActive(cur)
    }
    fn()
    // 滚动容器是 Layout 里的 .page（overflow:auto），scroll 事件不上冒泡，必须用捕获阶段监听
    window.addEventListener('scroll', fn, { passive: true, capture: true })
    return () => window.removeEventListener('scroll', fn, { capture: true })
  }, [])

  return (
    <div className="page">
      <div className="gd-head">
        <div>
          <h1>使用说明</h1>
          <p className="muted">兵棋对抗系统操作文档：开局、编剧本、生成六角格、地图判读、下指令、控局、权限与排错。</p>
        </div>
        <div className="gd-head-actions">
          <Link className="btn btn-primary" to="/new">去创建副本</Link>
          <Link className="btn" to="/lobby">去大厅</Link>
        </div>
      </div>

      <div className="gd-grid">
        <nav className="gd-toc">
          {CHAPTERS.map((c) => (
            <a key={c.id} href={`#${c.id}`} className={active === c.id ? 'on' : ''}>{c.title}</a>
          ))}
        </nav>

        <div className="gd-body">
          {CHAPTERS.map((c) => (
            <section key={c.id} id={c.id} className="gd-ch">
              <h2>{c.title}</h2>
              {c.secs.map((s, i) => (
                <div className="gd-card" key={i}>
                  <h3>{s.h}</h3>
                  {s.lead && <p className="gd-lead">{s.lead}</p>}
                  {s.steps && (
                    <ol className="gd-steps">
                      {s.steps.map((st, j) => {
                        const o = typeof st === 'string' ? { do: st } : st
                        return (
                          <li key={j}>
                            <b>{o.do}</b>
                            {o.note && <span className="gd-note">{o.note}</span>}
                          </li>
                        )
                      })}
                    </ol>
                  )}
                  {s.cards && (
                    <div className="gd-cards">
                      {s.cards.map((cd, j) => <div key={j}><b>{cd.t}</b><span>{cd.d}</span></div>)}
                    </div>
                  )}
                  {s.keys && (
                    <dl className="gd-keys">
                      {s.keys.map((kv, j) => <div key={j}><dt>{kv.k}</dt><dd>{kv.v}</dd></div>)}
                    </dl>
                  )}
                  {s.tips && (
                    <ul className="gd-tips">
                      {s.tips.map((t, j) => <li key={j}>{t}</li>)}
                    </ul>
                  )}
                </div>
              ))}
            </section>
          ))}
        </div>
      </div>
    </div>
  )
}
